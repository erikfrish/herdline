/**
 * Status dots, chips and bars outside Chat. They are the same on every client
 * and in both modes of the default palette.
 */
@Immutable
data class StatusColors(val working: Color, val blocked: Color, val done: Color, val idle: Color) {
    fun of(status: AgentStatus): Color = when (status) {
        AgentStatus.Working -> working
        AgentStatus.Blocked -> blocked
        AgentStatus.Done -> done
        AgentStatus.Idle -> idle
        AgentStatus.Unknown -> Color.Transparent
    }
}

/**
 * Chat's roles. The session accent is not one
 * of them: Chat mixes it toward [accentTextToward] by [accentTextMix] to get
 * its text-safe tint.
 */
@Immutable
data class ChatTokens(
    val bg: Color,
    val surf: Color,
    val userBubble: Color,
    val codeChip: Color,
    val codeBg: Color,
    val border: Color,
    val rule: Color,
    val text: Color,
    val muted: Color,
    val dim: Color,
    val accentTextToward: Color,
    val accentTextMix: Float,
    val working: Color,
    val blocked: Color,
    val done: Color,
    val err: Color,
    val warnBg: Color,
    val errBg: Color,
)

/** Glass tints, and the opaque fills of menus and snackbars, which have nothing to blur. */
@Immutable
data class GlassTokens(
    val tint: Color,
    val strongTint: Color,
    val rim: Color,
    val shadow: Color,
    val menu: Color,
    val snackbar: Color,
    val onSnackbar: Color,
)

/** Every colour one mode of a palette paints. */
@Immutable
class ThemeTokens(
    val dark: Boolean,
    val material: ColorScheme,
    val chat: ChatTokens,
    /** Dots, pills and bars. */
    val status: StatusColors,
    /** Status words, legible on the page and its first surface. */
    val statusText: StatusColors,
    val glass: GlassTokens,
    /** The [TerminalSchemes] id this mode pairs with. */
    val terminalScheme: String,
)

/**
 * A complete app palette. [id] is stored in settings and never renamed. A
 * palette without [light] is dark only: in light mode the app wears Herdline's.
 */
@Immutable
class AppPalette(val id: String, val name: String, private val light: ThemeTokens?, val dark: ThemeTokens) {
    val darkOnly: Boolean get() = light == null

    fun tokens(dark: Boolean): ThemeTokens = if (dark) this.dark else light ?: AppPalettes.Herdline.tokens(false)
}

