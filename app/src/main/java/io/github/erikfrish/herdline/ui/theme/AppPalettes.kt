    private val DynamicErrorDark = Color(0xFFF07D6D)
    private val DynamicErrorLight = Color(0xFFB1392A)

    /**
     * Material You: the device's [scheme] with Herdline's fixed meaning on top
     *. Surfaces and accents follow the wallpaper; status, the
     * warning and refusal fills and the terminal do not. Every text colour is
     * checked against this live scheme's six page tiers and moved along its
     * own hue until it reads, since a device palette (or its contrast
     * setting) can differ from any simulation.
     */
    fun dynamicTokens(scheme: ColorScheme, dark: Boolean): ThemeTokens {
        val toward = if (dark) Color.White else Color.Black
        val tiers = with(scheme) {
            listOf(surface, surfaceContainerLowest, surfaceContainerLow, surfaceContainer, surfaceContainerHigh, surfaceContainerHighest)
        }
        val material = scheme.withAccent(scheme.primary).copy(
            onSurfaceVariant = ensureContrast(scheme.onSurfaceVariant, tiers, 4.5f, toward),
            outline = ensureContrast(scheme.outline, tiers, 3f, toward),
        )
        fun text(color: Color) = ensureContrast(color, tiers, 4.5f, toward)
        val fixed = if (dark) DynamicStatusDark else DynamicStatusLight
        // Idle is the neutral glyph, drawn in the guarded onSurfaceVariant like Lost.
        val status = StatusColors(
            working = text(fixed.working),
            blocked = text(fixed.blocked),
            done = text(fixed.done),
            idle = material.onSurfaceVariant,
        )
        val herdline = Herdline.tokens(dark).chat
        return tokens(
            dark = dark,
            material = material,
            chat = ChatTokens(
                bg = material.background,
                surf = material.surfaceContainerLow,
                userBubble = material.surfaceContainer,
                codeChip = material.surfaceContainerHighest,
                codeBg = material.surfaceContainerLowest,
                border = material.outlineVariant,
                rule = material.outlineVariant,
                text = material.onSurface,
                muted = material.onSurfaceVariant,
                dim = material.onSurfaceVariant,
                accentTextToward = toward,
                accentTextMix = 0.55f,
                working = status.working,
                blocked = status.blocked,
                done = status.done,
                err = text(if (dark) DynamicErrorDark else DynamicErrorLight),
                // A held or refused notice looks the same on every wallpaper.
                warnBg = herdline.warnBg,
                errBg = herdline.errBg,
            ),
            status = status,
            statusText = status,
            menu = material.surfaceContainer,
            snackbar = material.inverseSurface,
            onSnackbar = material.inverseOnSurface,
            terminalScheme = Herdline.tokens(dark).terminalScheme,
        )
    }
